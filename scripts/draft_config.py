"""Profile a new company's files and write a draft config to review.

  python scripts/draft_config.py --company C --data-dir data/C --lines invoice_lines.csv --tree taxonomy_C.csv

Prints every column with fill rate, distinct count and examples, guesses the
role of each column (amount, date, supplier, description, status, ...) and
writes configs/<company>.yaml. Every guess is marked for review.
"""
import argparse
import os
import re
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from spendcube.clean import parse_dates, parse_numbers  # noqa: E402
from spendcube.config import read_table  # noqa: E402

ROLES = {
    "id": r"(^|_)(line|record|row|item)?_?id$|line_?id|record_?id|^id$",
    "amount": r"amount|amt|value|net|spend|total|price_total|line_total|extended",
    "gross_hint": r"gross|incl|with_?tax|with_?vat",
    "tax_rate": r"vat_?rate|tax_?rate|vat_?%|tax_?%",
    "tax_amount": r"vat_?amount|tax_?amount|^vat$|^tax$",
    "currency": r"^curr|currency|ccy|cur$",
    "fx_rate": r"rate|fx|exchange",
    "date": r"date|posted|posting|period",
    "supplier": r"supplier|vendor|payee|creditor",
    "supplier_id": r"(supplier|vendor|payee|creditor).*(id|no|num|code)$",
    "description": r"desc|text|item|material|product|service|narrat|memo|line_?text",
    "item_code": r"material|item_?(no|num|code)|sku|part_?(no|num)|product_?(code|id)",
    "status": r"status|state|approval",
    "quantity": r"^qty|quantity",
    "po": r"po_?(no|num|number|ref)|purchase_?order|^po$",
    "invoice": r"invoice_?(no|num|number|id)?$|^inv",
    "gl": r"gl|account|ledger|nominal",
    "cost_centre": r"cost_?cent|cc$|department|dept",
}


def profile(df):
    rows = []
    for c in df.columns:
        s = df[c]
        nn = s.notna() & (s.astype(str).str.strip() != "")
        v = s[nn].astype(str)
        num = parse_numbers(v.head(2000)).notna().mean() if len(v) else 0
        dt = (parse_dates(v.head(2000))[1] == "").mean() if len(v) else 0
        rows.append(dict(col=c, fill=round(nn.mean(), 3), distinct=v.nunique(), numeric=round(num, 2),
                         dateish=round(dt, 2), avg_len=round(v.str.len().mean(), 1) if len(v) else 0,
                         examples=" | ".join(v.drop_duplicates().head(4).str[:30])))
    return pd.DataFrame(rows)


def guess(prof, n):
    g = {}
    name = lambda c: re.sub(r"[^a-z0-9]+", "_", c.lower())
    for r in prof.itertuples():
        c = name(r.col)
        for role, rx in ROLES.items():
            if re.search(rx, c):
                g.setdefault(role, []).append(r)
    pick = {}
    ids = [r for r in prof.itertuples() if r.distinct == n and r.fill == 1.0]
    pick["id"] = (g.get("id") or ids or [None])[0]
    amt = [r for r in g.get("amount", []) if r.numeric > 0.9]
    pick["amount"] = max(amt, key=lambda r: r.distinct, default=None)
    dates = [r for r in g.get("date", []) if r.dateish > 0.5]
    pick["date"] = dates
    sup = [r for r in g.get("supplier", []) if r.numeric < 0.5 and r.avg_len > 4]
    pick["supplier"] = max(sup, key=lambda r: r.avg_len, default=None)
    pick["supplier_id"] = (g.get("supplier_id") or [None])[0]
    desc = [r for r in g.get("description", []) if r.numeric < 0.5]
    pick["description"] = sorted(desc, key=lambda r: -r.avg_len)[:2]
    for role in ["status", "currency", "quantity", "po", "invoice", "tax_rate", "tax_amount", "cost_centre", "item_code"]:
        pick[role] = (g.get(role) or [None])[0]
    pick["gl"] = [r for r in g.get("gl", []) if r.numeric < 0.9][:1]
    return pick


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--company", required=True)
    ap.add_argument("--data-dir", required=True)
    ap.add_argument("--lines", required=True)
    ap.add_argument("--tree", required=True)
    ap.add_argument("--currency", default="USD")
    a = ap.parse_args()
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    ddir = a.data_dir if os.path.isabs(a.data_dir) else os.path.join(root, a.data_dir)
    df = read_table(os.path.join(ddir, a.lines))
    tree = read_table(os.path.join(ddir, a.tree))
    pd.set_option("display.width", 250); pd.set_option("display.max_colwidth", 80); pd.set_option("display.max_rows", 500)
    print(f"{a.lines}: {len(df):,} rows x {df.shape[1]} cols")
    prof = profile(df)
    print(prof.to_string(index=False))
    print(f"\n{a.tree}: columns {list(tree.columns)}; {len(tree)} rows")
    print(tree.head(8).to_string(index=False))
    p = guess(prof, len(df))
    for c in df.columns:
        vc = df[c].nunique()
        if 1 < vc <= 25:
            print(f"\nvalues of {c}: {df[c].value_counts(dropna=False).head(25).to_dict()}")

    col = lambda r: r.col if r is not None else None
    lines = [f"# DRAFT generated by scripts/draft_config.py - review every line marked REVIEW",
             f"company: {a.company}", f"output_name: {a.company}", f"data_dir: {a.data_dir}",
             f"reporting_currency: {a.currency}", "", "taxonomy:", f"  file: {a.tree}",
             f"  level_columns: {list(tree.columns)}   # REVIEW: name columns only, L1..L4", "",
             "sources:", "  - name: lines", "    role: primary", f"    file: {a.lines}",
             f"    id_column: {col(p['id'])}   # REVIEW"]
    gross = p["amount"] is not None and re.search(ROLES["gross_hint"], p["amount"].col.lower())
    am = f"    amount: {{column: {col(p['amount'])}, gross: {'true' if gross else 'false'}"
    if gross and p["tax_rate"] is not None:
        am += f", vat_rate_column: {p['tax_rate'].col}"
    elif gross and p["tax_amount"] is not None:
        am += f", tax_amount_column: {p['tax_amount'].col}"
    lines.append(am + "}   # REVIEW: is it net of tax?")
    if p["currency"] is not None:
        lines.append(f"    currency: {{column: {p['currency'].col}}}   # REVIEW: add rate_column / fx file if not all {a.currency}")
    else:
        lines.append(f"    currency: {{fixed: {a.currency}}}   # REVIEW")
    lines.append(f"    date: {{columns: {[r.col for r in p['date']]}, dayfirst: true}}   # REVIEW")
    sup = {}
    if p["supplier"] is not None:
        sup["name_column"] = p["supplier"].col
    if p["supplier_id"] is not None and p["supplier_id"] is not p["supplier"]:
        sup["id_column"] = p["supplier_id"].col
    lines.append(f"    supplier: {sup}   # REVIEW".replace("'", ""))
    lines.append(f"    description: {[r.col for r in p['description']]}   # REVIEW".replace("'", ""))
    for role, key in [("item_code", "item_code"), ("quantity", "quantity")]:
        if p[role] is not None:
            lines.append(f"    {key}: {p[role].col}   # REVIEW")
    if p["po"] is not None:
        lines.append(f"    po: {{column: {p['po'].col}}}")
    if p["invoice"] is not None:
        lines.append(f"    invoice: {{column: {p['invoice'].col}}}")
    if p["status"] is not None:
        lines.append(f"    status: {{column: {p['status'].col}}}   # REVIEW the values printed above")
    if p["gl"]:
        lines.append(f"    classifier_text: [{p['gl'][0].col}]   # REVIEW: extra text that helps classify")
    lines.append("    duplicate_keys: ALL_SOURCE_COLUMNS   # a line exported twice is identical except its id")
    lines.append("")
    lines.append("exclusion_rules: []   # REVIEW: company-specific NON_PROCUREMENT rules (GL accounts, intercompany vendors)")
    lines.append("transfer_from: []")
    out = os.path.join(root, "configs", f"{a.company}.yaml")
    if os.path.exists(out):
        out = out.replace(".yaml", "_draft.yaml")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
